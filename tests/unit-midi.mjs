import { messageKey, describeKey, Midi } from '../src/js/midi.js';
globalThis.performance = globalThis.performance || { now: () => Date.now() };
let total = 0, failed = 0;
const eq = (name, got, want) => { total++; const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) failed++; console.log((ok ? '  ✔ ' : '  ✘ ') + name + (ok ? '' : ` — obtuvo ${JSON.stringify(got)}, esperado ${JSON.stringify(want)}`)); };
console.log('\nPedal / MIDI');
eq('Nota encendida → clave; nota con velocidad 0 (soltar) y nota apagada → nada', [messageKey([0x90, 60, 100]), messageKey([0x90, 60, 0]), messageKey([0x80, 60, 64])], ['n:60:1', null, null]);
eq('Pedal (CC 64): pisar (127) sí, soltar (0) y valores bajos no', [messageKey([0xb0, 64, 127]), messageKey([0xb0, 64, 0]), messageKey([0xb0, 64, 30])], ['c:64:1', null, null]);
eq('Cambio de programa y canal 5', [messageKey([0xc0, 7]), messageKey([0x94, 36, 90])], ['p:7:1', 'n:36:5']);
eq('Reloj MIDI y mensajes de sistema se ignoran', [messageKey([0xf8]), messageKey([0xfe]), messageKey([0xf0, 1, 2])], [null, null, null]);
eq('Descripción legible', [describeKey('n:60:1'), describeKey('c:64:2'), describeKey('p:3:1')], ['Nota 60 · canal 1', 'Pedal/control 64 · canal 2', 'Programa 3 · canal 1']);
const m = new Midi(); const events = [];
m.addEventListener('action', (e) => events.push(['action', e.detail.action]));
m.addEventListener('learned', (e) => events.push(['learned', e.detail.action, e.detail.key]));
m.handle([0xb0, 64, 127]);
eq('Sin asignar, un botón no hace nada', events.length, 0);
await new Promise((r) => setTimeout(r, 200));
m.learn('toggle'); m.handle([0xb0, 64, 127]);
eq('Aprender: el siguiente botón queda asignado a la acción', [events[0], m.keyOf('toggle')], [['learned', 'toggle', 'c:64:1'], 'c:64:1']);
await new Promise((r) => setTimeout(r, 200));
m.handle([0xb0, 64, 127]);
eq('Ya asignado: pisar el botón dispara la acción', events[1], ['action', 'toggle']);
m.handle([0xb0, 64, 127]);
eq('Rebote: dos pisadas en menos de 150 ms cuentan una sola vez', events.length, 2);
await new Promise((r) => setTimeout(r, 200));
m.learn('nextSec'); m.handle([0x90, 62, 100]); await new Promise((r) => setTimeout(r, 200));
m.learn('prevSec'); m.handle([0x90, 62, 100]);
eq('Un botón solo puede tener una acción (reasignarlo quita la anterior)', [m.keyOf('nextSec'), m.keyOf('prevSec')], [null, 'n:62:1']);
m.learn('fade'); m.cancelLearn(); m.handle([0x90, 70, 100]);
eq('Cancelar el aprendizaje no asigna nada', m.keyOf('fade'), null);
console.log(failed ? `\n${failed} de ${total} fallaron` : `\nMIDI OK (${total} comprobaciones)`);
process.exit(failed ? 1 : 0);
